import * as path from 'path';

// Pure helpers for repairing a Cook-generated OBJ download that ships textures but no material
// library (.mtl). When the source master model was ingested without its .mtl, Cook emits an OBJ
// (carrying a dangling mtllib/usemtl reference) plus diffuse/normal textures with nothing binding
// them. We fabricate a minimal .mtl so the stored and published package is internally valid; the
// user is still warned, and the model is allowed through. Kept free of storage/zip I/O so the
// synthesis logic is unit-testable; the zip orchestration lives in JobCookSIGenerateDownloads.

const IMAGE_EXTENSIONS: Set<string> = new Set(['.jpg', '.jpeg', '.png', '.tif', '.tiff', '.bmp', '.tga']);

export interface ObjPackageShape {
    objFile?: string;      // first .obj entry (full path within the zip)
    hasMtl: boolean;       // any .mtl entry present
    images: string[];      // image entries (full paths within the zip)
}

// Classify the entries of a package into the parts relevant to material repair.
export function inspectObjPackage(files: string[]): ObjPackageShape {
    let objFile: string | undefined = undefined;
    let hasMtl: boolean = false;
    const images: string[] = [];
    for (const file of files) {
        const ext: string = path.extname(file).toLowerCase();
        if (ext === '.obj') {
            if (!objFile)
                objFile = file;
        } else if (ext === '.mtl')
            hasMtl = true;
        else if (IMAGE_EXTENSIONS.has(ext))
            images.push(file);
    }
    return { objFile, hasMtl, images };
}

// True only for the single case we repair: an OBJ package shipping textures but no material library.
export function objPackageNeedsMtl(shape: ObjPackageShape): boolean {
    return !!shape.objFile && !shape.hasMtl && shape.images.length > 0;
}

// Pull the material-library (mtllib) and material (usemtl) names an OBJ references, if any. Both
// appear near the top of the file for a single-material mesh; scanning stops once both are found.
export function parseObjMaterialRefs(objText: string): { mtllib?: string; usemtl?: string } {
    let mtllib: string | undefined = undefined;
    let usemtl: string | undefined = undefined;
    for (const rawLine of objText.split(/\r?\n/)) {
        const line: string = rawLine.trim();
        if (!mtllib && /^mtllib\s+/i.test(line))
            mtllib = path.basename(line.replace(/^mtllib\s+/i, '').trim());
        else if (!usemtl && /^usemtl\s+/i.test(line))
            usemtl = line.replace(/^usemtl\s+/i, '').trim();
        if (mtllib && usemtl)
            break;
    }
    return { mtllib, usemtl };
}

// Pick a diffuse and a normal texture from the packaged images by filename convention. The normal
// map is matched first so it is never also chosen as the diffuse; the diffuse falls back to the
// first non-normal image when no name matches. Returns basenames, suitable for an .mtl reference
// alongside the geometry (Cook download packages are flat).
export function classifyPackageTextures(images: string[]): { diffuse?: string; normal?: string } {
    const names: string[] = images.map(image => path.basename(image));
    const normal: string | undefined = names.find(name => /normal|_nml|-nml|(^|[_-])norm([_-]|\.)/i.test(name));
    let diffuse: string | undefined = names.find(name =>
        name !== normal && /diffuse|albedo|basecolou?r|base[_-]?color|(^|[_-])colou?r([_-]|\.)|(^|[_-])kd([_-]|\.)/i.test(name));
    if (!diffuse)
        diffuse = names.find(name => name !== normal); // fallback: first non-normal image
    return { diffuse, normal };
}

// Build a minimal Wavefront .mtl defining one material with the given diffuse/normal maps. Only the
// maps that were found are emitted; a package with neither still yields a valid (untextured) material.
export function buildMinimalMtl(materialName: string, diffuse?: string, normal?: string): string {
    const lines: string[] = [
        '# Minimal material library generated by Packrat to complete an OBJ package shipped without one.',
        `newmtl ${materialName}`,
        'Ka 1.0000 1.0000 1.0000',
        'Kd 1.0000 1.0000 1.0000',
        'Ks 0.0000 0.0000 0.0000',
        'd 1.0000',
        'illum 2',
    ];
    if (diffuse)
        lines.push(`map_Kd ${diffuse}`);
    if (normal)
        lines.push(`map_Bump ${normal}`);
    return lines.join('\n') + '\n';
}
